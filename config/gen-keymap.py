#!/usr/bin/env python3
"""Generate Linux console keymap for HTC ChaCha hardware keyboard.

Layers (keymaps 0-5,8,12): plain, shift, altgr(FN), shift+altgr, ctrl, shift+ctrl, alt, ctrl+alt.
FN (keycode 56) = AltGr: symbols printed on the keys (same as CyanogenMod's chacha-keypad.kcm).
SYM (183) = Control (FN+SYM = 0). Green call (231) = Escape. Red call (107) = Alt.
Facebook key (184) = '|'. Shift+FN adds characters missing from the printed legend.
"""
import sys

# letter: (FN symbol, Shift+FN extra) — FN layer from chacha-keypad.kcm "alt:"
letters = {
    'q': ('parenleft', 'bracketleft'), 'w': ('one', 'braceleft'),
    'e': ('two', 'less'), 'r': ('three', 'greater'),
    't': ('exclam', 'bar'), 'y': ('less', 'greater'),  # FN+y: <, Shift+FN+y: > (instead of £)
    'u': ('dollar', 'asciitilde'), 'i': ('percent', 'percent'),
    'o': ('ampersand', 'ampersand'), 'p': ('at', 'at'),
    'a': ('parenright', 'bracketright'), 's': ('four', 'braceright'),
    'd': ('five', 'five'), 'f': ('six', 'six'),
    'g': ('slash', 'backslash'), 'h': ('underscore', 'underscore'),
    'j': ('minus', 'grave'), 'k': ('plus', 'asciicircum'),
    'l': ('equal', 'equal'), 'z': ('seven', 'seven'),
    'x': ('eight', 'eight'), 'c': ('nine', 'nine'),
    'v': ('asciicircum', 'U+20AC'), 'b': ('apostrophe', 'apostrophe'),  # FN+v: ^, € moved to Shift+FN
    'n': ('quotedbl', 'quotedbl'), 'm': ('colon', 'colon'),
}
codes = dict(zip('qwertyuiop', range(16, 26)))
codes.update(zip('asdfghjkl', range(30, 39)))
codes.update(zip('zxcvbnm', range(44, 51)))

out = ['# HTC ChaCha console keymap (generated by gen-keymap.py)',
       'charset "iso-8859-15"', 'keymaps 0-5,8,12', 'strings as usual', '']

def key(code, *cols):
    out.append(f'keycode {code:3d} = ' + ' '.join(cols))

for l, (fn, sfn) in letters.items():
    key(codes[l], '+' + l, '+' + l.upper(), fn, sfn,
        f'Control_{l}', f'Control_{l}', f'Meta_{l}', f'Meta_Control_{l}')

V = 'VoidSymbol'
key(14, 'Delete', 'Delete', 'Remove', 'Remove', 'BackSpace', 'BackSpace', 'Meta_Delete', 'Meta_BackSpace')  # DEL
key(15, 'Tab', 'asterisk', 'asterisk', 'asterisk', 'Tab', 'Tab', 'Meta_Tab', 'Meta_Tab')          # Tab / *
key(28, 'Return', 'Return', 'Return', 'Return', 'Return', 'Return', 'Meta_Control_m', 'Meta_Control_m')
key(51, 'comma', 'less', 'numbersign', 'less', V, V, 'Meta_comma', V)                               # , #
key(52, 'period', 'greater', 'colon', 'greater', V, V, 'Meta_period', V)                           # camera key = .
key(214, 'question', 'question', 'semicolon', 'semicolon', 'Delete', 'Delete', 'Meta_question', V) # ? ;
key(57, 'space', 'space', 'space', 'space', 'nul', 'nul', 'Meta_space', 'Meta_nul')
key(42, 'Shift', 'Shift', 'Shift', 'Shift', 'Shift', 'Shift', 'Shift', 'Shift')
key(56, 'AltGr', 'AltGr', 'AltGr', 'AltGr', 'AltGr', 'AltGr', 'AltGr', 'AltGr')                     # FN
key(183, 'Control', 'Control', 'zero', 'zero', 'Control', 'Control', 'Control', 'Control')          # SYM
key(107, 'Alt', 'Alt', 'Alt', 'Alt', 'Alt', 'Alt', 'Alt', 'Alt')                                     # red call
key(231, 'Escape', 'Escape', 'Escape', 'Escape', 'Escape', 'Escape', 'Meta_Escape', 'Meta_Escape') # green call
key(184, 'bar', 'bar', 'bar', 'bar', V, V, 'Meta_bar', V)                                           # facebook
# Arrows; FN+arrows = PgUp/PgDn/Home/End; Shift+Up/Down = console scrollback
key(103, 'Up', 'Scroll_Backward', 'Prior', 'Prior', 'Up', 'Up', 'Up', 'Up')
key(108, 'Down', 'Scroll_Forward', 'Next', 'Next', 'Down', 'Down', 'Down', 'Down')
key(105, 'Left', 'Left', 'Find', 'Find', 'Left', 'Left', 'Decr_Console', 'Left')
key(106, 'Right', 'Right', 'Select', 'Select', 'Right', 'Right', 'Incr_Console', 'Right')
key(115, 'Prior', 'Scroll_Backward', 'Prior', 'Prior', 'Prior', 'Prior', 'Prior', 'Prior')         # vol up
key(114, 'Next', 'Scroll_Forward', 'Next', 'Next', 'Next', 'Next', 'Next', 'Next')                 # vol down
key(116, V, V, V, V, V, V, V, V)                                                                   # power
sys.stdout.write('\n'.join(out) + '\n')
